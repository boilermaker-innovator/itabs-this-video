// One finished deck in the same shape as the AI decks.
export function demoDeck(sample, type) {
  const s = SAMPLES[sample], t = TYPES[type];
  if (!s || !t) return null;
  return {
    videoTitle: s.fullTitle, channel: s.by, videoId: "", lang: "en",
    forWho: t.forWho, youLabel: t.youLabel, demo: { sample, type },
    cards: s.cards.map((x) => ({
      band: x.band, colors: x.colors, time: "", seconds: 0, headline: x.headline, summary: x.summary,
      buttons: [{ you: true, title: t.youLabel, text: x.you[type] }, ...x.gold.map(([type2, text]) => ({ title: type2, type: type2, text }))],
    })),
  };
}
